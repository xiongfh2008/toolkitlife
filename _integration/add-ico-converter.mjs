const enHome = { name: "ICO Converter", description: "Convert images into multi-size ICO icons and extract ICO frames back to PNG images.", category: "Design", icon: "⊞" };

for (const locale of ["en", "zh", "ja", "ko", "ru", "es", "de", "fr", "pt"]) {
  const p = `messages/${locale}.json`;
  const m = JSON.parse(fs.readFileSync(p, "utf8"));
  if (m.tools["ico-converter"]) {
    console.log(`${locale}: already present, skipped`);
    continue;
  }
  const o = overrides[locale];
  const block = o ? o.block : en;
  const homeEntry = o ? o.home : enHome;
  const relatedName = o ? o.relatedName : "ICO Converter";

  m.tools["ico-converter"] = block;
  m.home.tools["ico-converter"] = homeEntry;
  for (const target of relatedTargets) {
    const rt = m.tools[target]?.relatedTools;
    if (Array.isArray(rt) && !rt.some((x) => x.href === "/tools/ico-converter")) {
      rt.push({ name: relatedName, href: "/tools/ico-converter" });
    }
  }
  fs.writeFileSync(p, JSON.stringify(m, null, 2) + "\n");
  console.log(`${locale}: ico-converter added`);
}
