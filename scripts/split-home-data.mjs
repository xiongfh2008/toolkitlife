import fs from "fs";
import path from "path";

/**
 * Split src/data/home.ts into per-consumer modules so tool pages don't ship
 * homepage-only data (scene slug lists + localized search aliases):
 *
 *  - scenes.ts          → POPULAR_TOOLS / HOME_SCENES (+ types)   [home page]
 *  - search-aliases.ts  → SEARCH_ALIASES                          [home page]
 *  - scene-of-slug.ts   → precomputed SCENE_OF_SLUG map           [tool pages]
 *
 * Part 1 runs once (when home.ts still exists); Part 2 can be re-run any time
 * scenes.ts changes to regenerate scene-of-slug.ts.
 */
const dataDir = path.join(process.cwd(), "src", "data");
const homePath = path.join(dataDir, "home.ts");
const scenesPath = path.join(dataDir, "scenes.ts");
const aliasesPath = path.join(dataDir, "search-aliases.ts");
const sceneMapPath = path.join(dataDir, "scene-of-slug.ts");

// --- Part 1: one-time split of home.ts into scenes.ts + search-aliases.ts ---
if (fs.existsSync(homePath)) {
  const src = fs.readFileSync(homePath, "utf8");

  const aliasesIdx = src.indexOf("/** Search aliases");
  if (aliasesIdx < 0) throw new Error("SEARCH_ALIASES block not found in home.ts");

  const scenesBlock = src.slice(0, aliasesIdx).trimEnd() + "\n";
  const aliasesBlock = src.slice(aliasesIdx).trimEnd() + "\n";

  const scenesHeader = `/**
 * Home page curation data — language-agnostic (slug-based).
 * Scenes group tools by task so the homepage isn't a flat wall of cards.
 * (SCENE_OF_SLUG lives in ./scene-of-slug.ts — regenerate with
 *  scripts/split-home-data.mjs.)
 */
`;
  fs.writeFileSync(
    scenesPath,
    scenesHeader + scenesBlock.slice(scenesBlock.indexOf("export interface HomeSceneGroup"))
  );

  const aliasesHeader = `/**
 * Search aliases: extra terms (often localized) matched against tool names on
 * the homepage search. Home-page only — keeps localized data out of the
 * shared/tool bundles.
 */
`;
  fs.writeFileSync(
    aliasesPath,
    aliasesHeader + aliasesBlock.slice(aliasesBlock.indexOf("export const SEARCH_ALIASES"))
  );

  console.log("split home.ts -> scenes.ts + search-aliases.ts");
}

// --- Part 2: generate scene-of-slug.ts from BASE_SCENES in scenes.ts ---
const scenesSrc = fs.readFileSync(scenesPath, "utf8");
const m = scenesSrc.match(/const BASE_SCENES: HomeScene\[\] = (\[[\s\S]*?\];)\n/);
if (!m) throw new Error("BASE_SCENES literal not found in scenes.ts");
const scenes = Function(`return ${m[1]}`)();

const map = {};
for (const s of scenes) {
  for (const t of s.tools ?? []) map[t] = s.key;
  for (const g of s.groups ?? []) for (const t of g.tools ?? []) map[t] = s.key;
}

const entries = Object.keys(map)
  .sort()
  .map((k) => `  "${k}": "${map[k]}",`)
  .join("\n");
const out = `/**
 * Precomputed slug → scene-key lookup used by tool-page breadcrumbs.
 * GENERATED by scripts/split-home-data.mjs — do not edit by hand.
 * Edit scenes in ./scenes.ts, then re-run: node scripts/split-home-data.mjs
 */
export const SCENE_OF_SLUG: Record<string, string> = {
${entries}
};
`;
fs.writeFileSync(sceneMapPath, out);
console.log(`scene-of-slug.ts: ${Object.keys(map).length} entries`);
